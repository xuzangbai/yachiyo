package dev.yachiyoc.render.esp;

/**
 * 目标渲染风格。
 *
 * <p>加新风格只做两件事：这里追加一个常量 + {@link EspRenderer#render} 里加一个分支。
 * 业务模块（aura、以后的水晶光环 …）只把枚举传进来，不认识具体画法。
 */
public enum EspMode {
    /**
     * 声纳扫描：以被攻击者碰撞箱中心为球心，半径从 0 扩散到设定值，
     * 扫描线只画在<b>碰撞箱表面和方块表面</b>上（球面与这些面的交线），到边缘淡出后重新来。
     */
    SONAR,
    /** 在目标身上上下往复、带拖尾的薰衣草光环。 */
    HALO
}
